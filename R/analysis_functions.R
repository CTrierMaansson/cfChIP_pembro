#Cluster patients based on gene enrichment
clusters_enrichment <- function(counts, #Gene level cfChIP enrichment returned by in_house_frag_counts()
                                meta, #cfChIP metadata for each sample
                                genes, #Gene SYMBOLs where the enrichment will separate patients
                                samples, #samples which should be used for the analysis
                                er = NULL, #Enrichment ratio cutoff
                                lib_size = NULL #Number of cfChIP fragments cutoff
                                ){
    #Filtering samples
    meta <- meta %>% 
        filter_samples(er = er,
                       lib_size = lib_size) %>% 
        filter(study_name == "Lung cancer") %>% 
        filter(sample %in% samples)
    df <- counts[genes,meta$sample] %>% 
        t()
    #Performing PCA
    pca_res <- prcomp(x = df, 
                      scale = TRUE,
                      center = TRUE)
    #Selecting first three principal components
    df <- pca_res$x[,1:3]
    #Performing clustering
    set.seed(4)
    cluster_res <- kmeans(x = df, 
                          centers = 2,
                          algorithm = "Hartigan-Wong")
    #Exporting cluster results
    center_df <- as.data.frame(cluster_res$centers)
    cluster_list <- split(names(cluster_res$cluster),
                          paste0("Cluster: ",cluster_res$cluster))
    cluster_df <- stack(cluster_list) %>% 
        dplyr::rename("sample" = "values") %>% 
        dplyr::rename("cluster" = "ind") %>% 
        left_join(meta, by = "sample")
    cluster_list <- split(cluster_df$patient,
                          cluster_df$cluster)
    return(cluster_list)
}

#Cluster patients based on gene enrichment dynamics
clusters_dynamic <- function(diff_df, #Gene enrichment dynamics returned by calc_diff()
                             meta, #cfChIP metadata for each sample
                             genes, #Gene SYMBOLs where the enrichment will separate patients
                             er = NULL, #Enrichment ratio cutoff
                             lib_size = NULL #Number of cfChIP fragments cutoff
                             ){
    #Filtering samples
    meta <- meta %>% 
        filter_samples(er = er,
                       lib_size = lib_size) %>% 
        filter(study_name == "Lung cancer") 
    c_meta <- meta %>% 
        group_by(patient) %>% 
        summarise(n = n())
    meta <- meta %>% 
        left_join(c_meta, by = "patient") %>% 
        filter(n == 2)
    #Formatting data and selecting patients
    df <- diff_df %>% 
        pivot_longer(-SYMBOL) %>% 
        dplyr::rename("patient" = "name") %>% 
        dplyr::rename("diff_counts" = "value") %>% 
        filter(patient %in% meta$patient) %>% 
        filter(SYMBOL %in% genes) %>% 
        pivot_wider(names_from = patient,
                    values_from = diff_counts) %>% 
        as.data.frame()
    rownames(df) <- df$SYMBOL
    df <- df %>% 
        dplyr::select(-SYMBOL) %>% 
        t()
    set.seed(2)
    #Performing clustering
    cluster_res <- kmeans(x = df, 
                          centers = 2,
                          algorithm = "Hartigan-Wong")
    #Exporting cluster results
    center_df <- as.data.frame(cluster_res$centers)
    cluster_list <- split(names(cluster_res$cluster),
                          paste0("Cluster: ",cluster_res$cluster))
    
    return(cluster_list)
}

#Calculating gene expression percentiles for RUV-III and GTEx data
calc_individual_percentile <- function(expression #RUV-III or GTEx expression dataset
                                       ){
    for(i in 1:ncol(expression)){
        print(round(i/ncol(expression)*100,2))
        sele_mat <- expression[,i]
        ranks <- rank(sele_mat,
                      ties.method = "max")
        if(i == 1){
            df <- data.frame(SYMBOL = names(sele_mat),
                             rank = ranks)
            rownames(df) <- NULL
        }else{
            ddf <- data.frame(SYMBOL = names(sele_mat),
                              rank = ranks)
            rownames(ddf) <- NULL
            df <- df %>% 
                left_join(ddf, by = "SYMBOL")
        }
        colnames(df)[i+1] <- colnames(expression)[i]
    }
    return(df)
}